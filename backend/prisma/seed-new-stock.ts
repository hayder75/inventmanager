const parsedData = rawData.map(line => {
  const [code, name, quantity, category, costPrice, sellingPrice] = line.split(',');
  return {
    code: code.trim(),
    name: name.trim(),
    quantity: parseInt(quantity.trim()),
    category: category.trim(),
    costPrice: parseFloat(costPrice.trim()),
    sellingPrice: parseFloat(sellingPrice.trim())
  };
});

async function main() {
  console.log('--- Cleaning up existing stock ---');
  await prisma.saleItem.deleteMany({});
  await prisma.sale.deleteMany({});
  await prisma.stockAdjustment.deleteMany({});
  await prisma.supplierPayment.deleteMany({});
  await prisma.stockEntry.deleteMany({});
  await prisma.product.deleteMany({});
  
  console.log('--- Updating with new stock ---');
  for (const item of parsedData) {
    try {
      const product = await prisma.product.create({
        data: {
          code: item.code,
          name: item.name,
          category: item.category,
          stockQty: item.quantity,
          costPrice: new Decimal(item.costPrice),
          sellingPrice: new Decimal(item.sellingPrice),
          unit: 'pcs',
          showOnWebsite: true
        }
      });
      if (item.quantity > 0) {
        await prisma.stockEntry.create({
          data: {
            productId: product.id,
            quantity: item.quantity,
            costPrice: new Decimal(item.costPrice),
            supplierName: 'Initial Update',
            status: 'FULLY_PAID'
          }
        });
      }
    } catch (e) {
      console.error(`Error creating product ${item.name}:`, e);
    }
  }
  console.log('--- Finished updating stock ---');
}

main()
  .catch(e => {
    console.error(e);
    process.exit(1);
  })
  .finally(async () => {
    await prisma.$disconnect();
  });
